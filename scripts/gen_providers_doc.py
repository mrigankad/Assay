"""Regenerate docs/PROVIDERS.md from backend/src/providers/catalog.py."""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from src.providers.catalog import PROVIDERS  # noqa: E402

KINDS = [("hyperscaler", "Clouds"), ("lab", "Model labs"), ("inference", "Inference APIs"),
         ("aggregator", "Gateways"), ("local", "Local runtimes"), ("cli", "CLI logins (opt-in)")]

out = ["# Model providers", "",
       "Assay detects these on start. Set the variables (or sign in / start the server) and press **Scan again** on the Models screen, or call `GET /api/providers?refresh=true`.",
       "", "Any model string LiteLLM understands also works directly: `ASSAY_MODEL=bedrock/...`, `ASSAY_MODEL_VERIFIER=gemini/...`.",
       "", "_Generated by `scripts/gen_providers_doc.py`; do not edit by hand._", ""]
for kind, label in KINDS:
    items = [p for p in PROVIDERS if p.kind == kind]
    if not items:
        continue
    out += [f"## {label}", "", "| | Provider | Detected from | Model prefix | Does |", "|---|---|---|---|---|"]
    for p in items:
        how = []
        if p.env:
            how.append(" or ".join("`" + " + ".join(g) + "`" for g in p.env))
        if p.files:
            how.append(" / ".join(f"`{f}`" for f in p.files if not f.startswith("%")))
        if p.port:
            how.append(f"`localhost:{p.port}`")
        if p.kind == "cli":
            how.append("binary on PATH + `ASSAY_ENABLE_" + p.id.upper() + "=1`")
        if p.id == "builtin":
            how.append("always (needs `fastembed`)")
        prefix = f"`{p.prefix}/`" if p.prefix else "built in"
        note = f" Needs {p.needs}." if p.needs else ""
        out.append(f"| <img src=\"../frontend/public/brand/providers/{p.id}.svg\" width=\"18\"/> | {p.name} | {'; '.join(how) or '-'} | {prefix} | {', '.join(sorted(p.caps))}.{note} |")
    out.append("")
out += ["## Notes", "",
        "- **AWS** follows the standard boto3 chain: env keys, `AWS_PROFILE`, SSO (`aws sso login`), web identity, ECS/EC2 roles. Set `AWS_REGION`.",
        "- **Azure** uses deployment names, not model names: `ASSAY_MODEL=azure/<deployment>`. Without a key, Entra ID (`az login`, managed identity) is used.",
        "- **Google Vertex** uses Application Default Credentials (`gcloud auth application-default login`). Set `VERTEXAI_PROJECT` and `VERTEXAI_LOCATION`.",
        "- **CLI logins** run the vendor's official CLI with your own account. Personal use only; not for shared servers or bulk indexing. Check each vendor's current terms.",
        "- Logos: LobeHub Icons (MIT) and simple-icons (CC0), recoloured; trademarks of their owners. See `frontend/public/brand/providers/LICENSES.md`.", ""]
(ROOT / "docs" / "PROVIDERS.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/PROVIDERS.md")
